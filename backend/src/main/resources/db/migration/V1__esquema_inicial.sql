-- =====================================================================
-- DroneMission Pro - Esquema inicial de la base de datos
-- Compatible con PostgreSQL 14+ y H2 (modo PostgreSQL).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Seguridad: roles, permisos y usuarios
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(30)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL,
    CONSTRAINT ck_roles_nombre CHECK (nombre IN ('ADMINISTRADOR','OPERADOR','PILOTO','TECNICO','CLIENTE'))
);

CREATE TABLE permisos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL
);

-- Relación N:M entre roles y permisos
CREATE TABLE rol_permisos (
    rol_id     BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    PRIMARY KEY (rol_id, permiso_id)
);

CREATE TABLE usuarios (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(80)  NOT NULL,
    apellidos           VARCHAR(80)  NOT NULL,
    correo              VARCHAR(120) NOT NULL UNIQUE,
    contrasena_hash     VARCHAR(100) NOT NULL,
    rol_id              BIGINT       NOT NULL REFERENCES roles(id),
    activo              BOOLEAN      NOT NULL DEFAULT TRUE,
    token_recuperacion  VARCHAR(64),
    token_expira_en     TIMESTAMP,
    ultimo_acceso       TIMESTAMP,
    creado_en           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_usuarios_rol ON usuarios(rol_id);

-- ---------------------------------------------------------------------
-- Clientes
-- ---------------------------------------------------------------------
CREATE TABLE clientes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo        VARCHAR(20)  NOT NULL,
    nombre      VARCHAR(150) NOT NULL,
    documento   VARCHAR(30)  NOT NULL UNIQUE,
    correo      VARCHAR(120) NOT NULL,
    telefono    VARCHAR(30)  NOT NULL,
    direccion   VARCHAR(200) NOT NULL,
    ciudad      VARCHAR(80)  NOT NULL,
    activo      BOOLEAN      NOT NULL DEFAULT TRUE,
    usuario_id  BIGINT       UNIQUE REFERENCES usuarios(id),
    creado_en   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_clientes_tipo CHECK (tipo IN ('PERSONA','EMPRESA'))
);

-- ---------------------------------------------------------------------
-- Pilotos y certificaciones
-- ---------------------------------------------------------------------
CREATE TABLE pilotos (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                VARCHAR(80)   NOT NULL,
    apellidos             VARCHAR(80)   NOT NULL,
    documento             VARCHAR(30)   NOT NULL UNIQUE,
    correo                VARCHAR(120)  NOT NULL UNIQUE,
    telefono              VARCHAR(30)   NOT NULL,
    numero_licencia       VARCHAR(40)   NOT NULL UNIQUE,
    vencimiento_licencia  DATE          NOT NULL,
    horas_vuelo           NUMERIC(10,2) NOT NULL DEFAULT 0,
    estado                VARCHAR(20)   NOT NULL DEFAULT 'DISPONIBLE',
    activo                BOOLEAN       NOT NULL DEFAULT TRUE,
    usuario_id            BIGINT        UNIQUE REFERENCES usuarios(id),
    creado_en             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pilotos_estado CHECK (estado IN ('DISPONIBLE','EN_MISION','NO_DISPONIBLE','LICENCIA_VENCIDA')),
    CONSTRAINT ck_pilotos_horas CHECK (horas_vuelo >= 0)
);

CREATE TABLE certificaciones_piloto (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id          BIGINT       NOT NULL REFERENCES pilotos(id) ON DELETE CASCADE,
    nombre             VARCHAR(120) NOT NULL,
    entidad_emisora    VARCHAR(120) NOT NULL,
    fecha_emision      DATE         NOT NULL,
    fecha_vencimiento  DATE,
    CONSTRAINT ck_cert_fechas CHECK (fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_emision)
);
CREATE INDEX ix_certificaciones_piloto ON certificaciones_piloto(piloto_id);

-- ---------------------------------------------------------------------
-- Drones y mantenimientos
-- ---------------------------------------------------------------------
CREATE TABLE drones (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo                  VARCHAR(20)   NOT NULL UNIQUE,
    nombre                  VARCHAR(100)  NOT NULL,
    fabricante              VARCHAR(80)   NOT NULL,
    modelo                  VARCHAR(80)   NOT NULL,
    numero_serie            VARCHAR(60)   NOT NULL UNIQUE,
    tipo                    VARCHAR(20)   NOT NULL,
    estado                  VARCHAR(20)   NOT NULL DEFAULT 'DISPONIBLE',
    capacidad_bateria_mah   INTEGER       NOT NULL,
    bateria_actual          INTEGER       NOT NULL DEFAULT 100,
    horas_vuelo             NUMERIC(10,2) NOT NULL DEFAULT 0,
    velocidad_maxima_kmh    INTEGER       NOT NULL,
    autonomia_minutos       INTEGER       NOT NULL,
    fecha_adquisicion       DATE          NOT NULL,
    ultimo_mantenimiento    DATE,
    proximo_mantenimiento   DATE,
    descripcion             VARCHAR(1000),
    activo                  BOOLEAN       NOT NULL DEFAULT TRUE,
    creado_en               TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_drones_tipo CHECK (tipo IN ('INSPECCION','AGRICULTURA','VIGILANCIA','TOPOGRAFIA','FOTOGRAFIA')),
    CONSTRAINT ck_drones_estado CHECK (estado IN ('DISPONIBLE','EN_MISION','EN_MANTENIMIENTO','FUERA_DE_SERVICIO')),
    CONSTRAINT ck_drones_bateria CHECK (bateria_actual BETWEEN 0 AND 100),
    CONSTRAINT ck_drones_capacidad CHECK (capacidad_bateria_mah > 0),
    CONSTRAINT ck_drones_horas CHECK (horas_vuelo >= 0)
);
CREATE INDEX ix_drones_estado ON drones(estado);

CREATE TABLE mantenimientos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drone_id       BIGINT        NOT NULL REFERENCES drones(id),
    tecnico_id     BIGINT        NOT NULL REFERENCES usuarios(id),
    tipo           VARCHAR(20)   NOT NULL,
    fecha          DATE          NOT NULL,
    descripcion    VARCHAR(1000) NOT NULL,
    costo          NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado         VARCHAR(20)   NOT NULL DEFAULT 'PROGRAMADO',
    proxima_fecha  DATE,
    observaciones  VARCHAR(1000),
    iniciado_en    TIMESTAMP,
    completado_en  TIMESTAMP,
    creado_en      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_mant_tipo CHECK (tipo IN ('PREVENTIVO','CORRECTIVO','CALIBRACION','REPARACION','INSPECCION')),
    CONSTRAINT ck_mant_estado CHECK (estado IN ('PROGRAMADO','EN_PROCESO','COMPLETADO','CANCELADO')),
    CONSTRAINT ck_mant_costo CHECK (costo >= 0)
);
CREATE INDEX ix_mantenimientos_drone ON mantenimientos(drone_id);
CREATE INDEX ix_mantenimientos_estado ON mantenimientos(estado);

-- ---------------------------------------------------------------------
-- Misiones, asignaciones y plan de vuelo
-- ---------------------------------------------------------------------
CREATE TABLE misiones (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20)   NOT NULL UNIQUE,
    nombre              VARCHAR(150)  NOT NULL,
    descripcion         VARCHAR(1000),
    tipo                VARCHAR(20)   NOT NULL,
    cliente_id          BIGINT        NOT NULL REFERENCES clientes(id),
    ubicacion           VARCHAR(200)  NOT NULL,
    latitud             DOUBLE PRECISION  NOT NULL,
    longitud            DOUBLE PRECISION  NOT NULL,
    altitud_objetivo_m  INTEGER       NOT NULL,
    fecha_programada    DATE          NOT NULL,
    hora_inicio         TIME          NOT NULL,
    hora_fin_estimada   TIME          NOT NULL,
    prioridad           VARCHAR(10)   NOT NULL,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'BORRADOR',
    objetivo            VARCHAR(500)  NOT NULL,
    observaciones       VARCHAR(1000),
    creado_por          BIGINT        NOT NULL REFERENCES usuarios(id),
    inicio_real         TIMESTAMP,
    fin_real            TIMESTAMP,
    creado_en           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_misiones_tipo CHECK (tipo IN ('INSPECCION','AGRICULTURA','VIGILANCIA','TOPOGRAFIA','FOTOGRAFIA','MONITOREO')),
    CONSTRAINT ck_misiones_prioridad CHECK (prioridad IN ('BAJA','MEDIA','ALTA','CRITICA')),
    CONSTRAINT ck_misiones_estado CHECK (estado IN ('BORRADOR','PENDIENTE','PROGRAMADA','EN_PREPARACION','EN_VUELO','PAUSADA','FINALIZADA','CANCELADA')),
    CONSTRAINT ck_misiones_horas CHECK (hora_fin_estimada > hora_inicio),
    CONSTRAINT ck_misiones_latitud CHECK (latitud BETWEEN -90 AND 90),
    CONSTRAINT ck_misiones_longitud CHECK (longitud BETWEEN -180 AND 180),
    CONSTRAINT ck_misiones_altitud CHECK (altitud_objetivo_m BETWEEN 5 AND 120)
);
CREATE INDEX ix_misiones_estado ON misiones(estado);
CREATE INDEX ix_misiones_cliente ON misiones(cliente_id);
CREATE INDEX ix_misiones_fecha ON misiones(fecha_programada);

-- Historial de asignaciones: una misión tiene a lo sumo una asignación activa.
-- Relación N:M entre misiones, drones y pilotos a lo largo del tiempo.
CREATE TABLE asignaciones_mision (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id         BIGINT    NOT NULL REFERENCES misiones(id) ON DELETE CASCADE,
    drone_id          BIGINT    NOT NULL REFERENCES drones(id),
    piloto_id         BIGINT    NOT NULL REFERENCES pilotos(id),
    asignado_por      BIGINT    NOT NULL REFERENCES usuarios(id),
    fecha_asignacion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    activa            BOOLEAN   NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_asignaciones_mision ON asignaciones_mision(mision_id, activa);
CREATE INDEX ix_asignaciones_drone ON asignaciones_mision(drone_id, activa);
CREATE INDEX ix_asignaciones_piloto ON asignaciones_mision(piloto_id, activa);

-- Plan de vuelo programado con anticipación: el drone virtual lo recorre en orden.
CREATE TABLE puntos_ruta (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id  BIGINT       NOT NULL REFERENCES misiones(id) ON DELETE CASCADE,
    orden      INTEGER      NOT NULL,
    latitud    DOUBLE PRECISION NOT NULL,
    longitud   DOUBLE PRECISION NOT NULL,
    altitud_m  INTEGER      NOT NULL,
    accion     VARCHAR(20)  NOT NULL,
    CONSTRAINT uq_puntos_ruta_orden UNIQUE (mision_id, orden),
    CONSTRAINT ck_puntos_accion CHECK (accion IN ('DESPEGUE','PASO','FOTO','VIDEO','ESCANEO','FUMIGACION','ATERRIZAJE'))
);

-- ---------------------------------------------------------------------
-- Telemetría simulada
-- ---------------------------------------------------------------------
CREATE TABLE telemetria (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id          BIGINT        NOT NULL REFERENCES misiones(id) ON DELETE CASCADE,
    registrado_en      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    latitud            DOUBLE PRECISION  NOT NULL,
    longitud           DOUBLE PRECISION  NOT NULL,
    altitud_m          DOUBLE PRECISION NOT NULL,
    velocidad_kmh      DOUBLE PRECISION NOT NULL,
    bateria            INTEGER       NOT NULL,
    distancia_m        DOUBLE PRECISION NOT NULL,
    temperatura_c      DOUBLE PRECISION NOT NULL,
    tiempo_vuelo_s     INTEGER       NOT NULL,
    punto_ruta_actual  INTEGER       NOT NULL,
    simulado           BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_telemetria_bateria CHECK (bateria BETWEEN 0 AND 100)
);
CREATE INDEX ix_telemetria_mision ON telemetria(mision_id, registrado_en);

-- ---------------------------------------------------------------------
-- Evidencias e incidentes
-- ---------------------------------------------------------------------
CREATE TABLE evidencias (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id        BIGINT        NOT NULL REFERENCES misiones(id) ON DELETE CASCADE,
    tipo             VARCHAR(20)   NOT NULL,
    nombre           VARCHAR(150)  NOT NULL,
    url              VARCHAR(500)  NOT NULL,
    descripcion      VARCHAR(1000),
    visible_cliente  BOOLEAN       NOT NULL DEFAULT TRUE,
    subido_por       BIGINT        NOT NULL REFERENCES usuarios(id),
    fecha            TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_evidencias_tipo CHECK (tipo IN ('FOTOGRAFIA','VIDEO','DOCUMENTO','ARCHIVO','OBSERVACION'))
);
CREATE INDEX ix_evidencias_mision ON evidencias(mision_id);

CREATE TABLE incidentes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mision_id       BIGINT        NOT NULL REFERENCES misiones(id) ON DELETE CASCADE,
    fecha           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo            VARCHAR(30)   NOT NULL,
    severidad       VARCHAR(10)   NOT NULL,
    descripcion     VARCHAR(1000) NOT NULL,
    registrado_por  BIGINT        REFERENCES usuarios(id),
    estado          VARCHAR(20)   NOT NULL DEFAULT 'ABIERTO',
    resolucion      VARCHAR(1000),
    CONSTRAINT ck_incidentes_tipo CHECK (tipo IN ('BATERIA_BAJA','PERDIDA_SENAL','OBSTACULO','ERROR_TECNICO','CLIMA','ATERRIZAJE_EMERGENCIA','OTRO')),
    CONSTRAINT ck_incidentes_severidad CHECK (severidad IN ('BAJA','MEDIA','ALTA','CRITICA')),
    CONSTRAINT ck_incidentes_estado CHECK (estado IN ('ABIERTO','EN_REVISION','RESUELTO'))
);
CREATE INDEX ix_incidentes_mision ON incidentes(mision_id);
CREATE INDEX ix_incidentes_fecha ON incidentes(fecha);

-- ---------------------------------------------------------------------
-- Reportes, auditoría y notificaciones
-- ---------------------------------------------------------------------
CREATE TABLE reportes (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo          VARCHAR(20)   NOT NULL,
    titulo        VARCHAR(200)  NOT NULL,
    mision_id     BIGINT        REFERENCES misiones(id) ON DELETE CASCADE,
    generado_por  BIGINT        REFERENCES usuarios(id),
    generado_en   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resumen       VARCHAR(2000) NOT NULL,
    CONSTRAINT ck_reportes_tipo CHECK (tipo IN ('MISION','DRONES','PILOTOS','MANTENIMIENTO'))
);
CREATE INDEX ix_reportes_mision ON reportes(mision_id);

CREATE TABLE auditoria (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      BIGINT        REFERENCES usuarios(id),
    correo_usuario  VARCHAR(120)  NOT NULL,
    accion          VARCHAR(40)   NOT NULL,
    entidad         VARCHAR(40)   NOT NULL,
    entidad_id      BIGINT,
    descripcion     VARCHAR(1000) NOT NULL,
    fecha           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_auditoria_fecha ON auditoria(fecha);

CREATE TABLE notificaciones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    titulo      VARCHAR(150) NOT NULL,
    mensaje     VARCHAR(500) NOT NULL,
    mision_id   BIGINT       REFERENCES misiones(id) ON DELETE CASCADE,
    leida       BOOLEAN      NOT NULL DEFAULT FALSE,
    fecha       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_notificaciones_usuario ON notificaciones(usuario_id, leida);
